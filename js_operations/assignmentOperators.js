//Assignment Operators (=, +=, -=, *=, /=, %=) 
// These operators are used to assign values to variables and perform arithmetic operations in a concise manner.

// Increase a bank balance by ₹5,000 using +=.

let bankBalance = 10000 // = is a assign value
bankBalance += 5000 // // += increases the value of the variable.
console.log("Your bank Balance is : ", bankBalance)

// Decrease a wallet balance after shopping using -=.
let walletBalance = 5000
walletBalance -= 4599
console.log("You Wallet Balance after Shopping is : ", walletBalance);

// Double a player's score using *=.
let PlayerScore = 100
PlayerScore *= 2
console.log("Player's New score is : ", PlayerScore)

// Divide a company's profit equally among departments using /=.
let companyProfit = 100000
companyProfit /= 5
console.log("The compay's profit equal divide in 5 deparments is : " , companyProfit)

// Find the remainder using %=.
let findRemainder = 30
findRemainder %= 4
console.log("The remainder is : ", findRemainder)

