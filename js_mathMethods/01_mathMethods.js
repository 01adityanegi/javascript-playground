// Here we learn Math methods in JavaScript.

// Print the value of Math.PI.
console.log(Math.PI); // 3.141592653589793

// Print the value of Math.E.
console.log(Math.E); // 2.718281828459045

// Find the absolute value of -25.
console.log(Math.abs(-25)); // 25

// Find the square root of 144.
console.log(Math.sqrt(144)); // 12

// Find the cube root of 125.
console.log(Math.cbrt(125)); // 5

// Find 5 raised to the power of 4.
console.log(Math.pow(5, 4)); // 625

// Find the maximum of 10, 45, 23, 89, 12.
console.log(Math.max(10, 45, 23, 89, 12)); // 89

// Find the minimum of 10, 45, 23, 89, 12.
console.log(Math.min(10, 45, 23, 89, 12)); // 10

// Round 7.6 to the nearest integer.
console.log(Math.round(7.6)); // 8

// Round down 8.9.
console.log(Math.floor(8.9)); // 8

// Round up 8.1.
console.log(Math.ceil(8.1)); // 9

// Remove the decimal part from 15.99.
console.log(Math.trunc(15.99)); // 15

// Find the sign of -15.
console.log(Math.sign(-15)); // -1

// Generate a random decimal number between 0 (inclusive) and 1 (exclusive).
console.log(Math.random()); // Example: 0.483726519